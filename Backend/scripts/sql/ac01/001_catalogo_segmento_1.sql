                Saldo, Estado, FechaCreacion, EsImputable, EsCuentaValuacion
            )
            SELECT @UltimoId + ROW_NUMBER() OVER (ORDER BY s.CodigoCuenta),
                   s.CodigoCuenta, s.NombreCuenta, s.Naturaleza, p.IdCuentaContable,
                   0, 1, SYSDATETIME(), s.EsImputable, s.EsCuentaValuacion
            FROM @Catalogo AS s
            LEFT JOIN Contabilidad.CuentasContables AS p
                ON p.CodigoCuenta COLLATE DATABASE_DEFAULT = s.CodigoCuentaSuperior
            WHERE LEN(s.CodigoCuenta) = @Nivel
              AND NOT EXISTS (
                  SELECT 1 FROM Contabilidad.CuentasContables AS c
                  WHERE c.CodigoCuenta COLLATE DATABASE_DEFAULT = s.CodigoCuenta
              );
            SET @Nuevas = @@ROWCOUNT;
            SET @UltimoId += @Nuevas;
        END;

        UPDATE c SET
            NombreCuenta = s.NombreCuenta,
            Naturaleza = s.Naturaleza,
            IdCuentaSuperior = p.IdCuentaContable,
            EsImputable = s.EsImputable,
            EsCuentaValuacion = s.EsCuentaValuacion,
            FechaModificacion = SYSDATETIME()
        FROM Contabilidad.CuentasContables AS c
        JOIN @Catalogo AS s ON s.CodigoCuenta = c.CodigoCuenta COLLATE DATABASE_DEFAULT
        LEFT JOIN Contabilidad.CuentasContables AS p
            ON p.CodigoCuenta COLLATE DATABASE_DEFAULT = s.CodigoCuentaSuperior
        WHERE LEN(s.CodigoCuenta) = @Nivel
          AND EXISTS (
              SELECT CONVERT(nvarchar(150), c.NombreCuenta) COLLATE Latin1_General_100_BIN2,
                     c.Naturaleza COLLATE DATABASE_DEFAULT,
                     c.IdCuentaSuperior, c.EsImputable, c.EsCuentaValuacion
              EXCEPT
              SELECT s.NombreCuenta COLLATE Latin1_General_100_BIN2,
                     s.Naturaleza, p.IdCuentaContable,
                     s.EsImputable, s.EsCuentaValuacion
          );

        SET @Nivel = CASE @Nivel WHEN 1 THEN 2 ELSE @Nivel + 2 END;
    END;

    IF EXISTS (
        SELECT 1
        FROM @Catalogo AS s
        LEFT JOIN Contabilidad.CuentasContables AS c ON c.CodigoCuenta COLLATE DATABASE_DEFAULT = s.CodigoCuenta
        LEFT JOIN Contabilidad.CuentasContables AS p ON p.IdCuentaContable = c.IdCuentaSuperior
        WHERE c.IdCuentaContable IS NULL
           OR ISNULL(p.CodigoCuenta, '') COLLATE DATABASE_DEFAULT <> ISNULL(s.CodigoCuentaSuperior, '')
           OR c.Naturaleza COLLATE DATABASE_DEFAULT <> s.Naturaleza
           OR c.EsCuentaValuacion <> s.EsCuentaValuacion
           OR c.EsImputable <> s.EsImputable
           OR CONVERT(nvarchar(150), c.NombreCuenta) COLLATE Latin1_General_100_BIN2
              <> s.NombreCuenta COLLATE Latin1_General_100_BIN2
    )
        THROW 56104, N'La carga no reprodujo la jerarquía y clasificación esperadas.', 1;

    COMMIT TRANSACTION;
END TRY
