    SELECT @UltimoId = ISNULL(MAX(IdCuentaContable), 0)
    FROM Contabilidad.CuentasContables WITH (TABLOCKX, HOLDLOCK);

    IF EXISTS (
        SELECT 1
        FROM Contabilidad.CuentasContables AS c
        JOIN @Catalogo AS s ON s.CodigoCuenta = c.CodigoCuenta COLLATE DATABASE_DEFAULT
        GROUP BY c.CodigoCuenta
        HAVING COUNT(*) > 1
    )
        THROW 56101, N'El catálogo existente tiene códigos duplicados.', 1;

    IF EXISTS (
        SELECT 1
        FROM @Catalogo AS s
        WHERE NOT EXISTS (
            SELECT 1 FROM Contabilidad.ElementoCUC AS e
            WHERE e.CodigoElemento COLLATE DATABASE_DEFAULT = LEFT(s.CodigoCuenta, 1)
        )
    )
        THROW 56102, N'Cargue primero los elementos 1 a 7 de ElementoCUC.', 1;

    IF EXISTS (
        SELECT 1
        FROM Contabilidad.CuentasContables AS c
        JOIN @Catalogo AS s ON s.CodigoCuenta = c.CodigoCuenta COLLATE DATABASE_DEFAULT
        LEFT JOIN Contabilidad.CuentasContables AS p
            ON p.IdCuentaContable = c.IdCuentaSuperior
        WHERE (c.Naturaleza COLLATE DATABASE_DEFAULT <> s.Naturaleza
            OR c.EsCuentaValuacion <> s.EsCuentaValuacion
            OR c.EsImputable <> s.EsImputable
            OR ISNULL(p.CodigoCuenta, '') COLLATE DATABASE_DEFAULT <> ISNULL(s.CodigoCuentaSuperior, ''))
          AND (c.Saldo <> 0 OR EXISTS (
              SELECT 1
              FROM Contabilidad.MovimientosContables AS m
              WHERE m.IdCuentaContable = c.IdCuentaContable
          ))
    )
